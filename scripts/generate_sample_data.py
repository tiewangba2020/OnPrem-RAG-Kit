def validate(verbose: bool = True) -> List[str]:
    problems: List[str] = []
    for q in QUESTIONS:
        targets = q.get("evidence_docs") or [q["doc_id"]]
        docs = [DOC_MAP[t] for t in targets if t in DOC_MAP]
        for fact in q["recall_facts"]:
            if not any(fact in d for d in docs):
                problems.append(f"{q['id']} recall_fact 未在文档中逐字命中: {fact!r}")
        if q.get("gold_row") and not any(q["gold_row"] in d for d in docs):
            problems.append(f"{q['id']} gold_row 未在文档中逐字命中")
        for ev in q["gold_evidence"]:
            if not any(ev in d for d in docs):
                problems.append(f"{q['id']} gold_evidence 未命中: {ev[:40]!r}...")
        if not q.get("gold_answer") or not q.get("naive_answer") or not q.get("advanced_answer"):
            problems.append(f"{q['id']} 缺少标准答案 / 失败样例 / 本方案答案")
        if q["answer_type"] == "table" and not q.get("gold_row"):
            problems.append(f"{q['id']} 表格题缺少 gold_row")
    if verbose:
        if problems:
            print(f"[warn] 题库校验发现 {len(problems)} 处问题：")
            for p in problems[:20]:
                print("   -", p)
        else:
            print(f"[ok]   题库校验通过：{len(QUESTIONS)} 题全部与文档逐字一致")
    return problems


