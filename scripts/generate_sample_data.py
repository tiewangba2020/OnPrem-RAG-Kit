def generate_bench_questions() -> tuple:
    """调用 generate_eval_set 生成规模化题库（20 人工 + 10 跨文档 + N 表格行派生）。"""
    try:
        import importlib.util

        spec = importlib.util.spec_from_file_location(
            "_gen_eval_set", Path(__file__).resolve().parent / "generate_eval_set.py")
        mod = importlib.util.module_from_spec(spec)          # type: ignore[arg-type]
        spec.loader.exec_module(mod)                         # type: ignore[union-attr]
        path, n = mod.write_questions()
        return str(Path(path).relative_to(ROOT)), n
    except Exception as exc:                                 # pragma: no cover
        print(f"[warn] 规模化题库生成失败（{type(exc).__name__}: {exc}），将只用 20 题演示集。")
        return "", 0


def generate_benchmark(try_measured: bool = True) -> tuple:
    """优先调用 core.evaluator 产出实测基准；不可用时只写压测数据，不伪造指标。"""
    if try_measured:
        try:
            if str(ROOT) not in sys.path:
                sys.path.insert(0, str(ROOT))
            from core.evaluator import BENCH_QUESTIONS, DEMO_QUESTIONS, run_full_benchmark  # type: ignore

            # 优先用规模化题库（121 题）；旧环境没生成过时退回 20 题演示集
            qpath = BENCH_QUESTIONS if BENCH_QUESTIONS.exists() else DEMO_QUESTIONS
            result = run_full_benchmark(questions_path=qpath, verbose=True,
                                        answer_mode="extractive")
            path = DATA_DIR / "benchmark_results.json"
            write_json(path, result)
            return str(path.relative_to(ROOT)), result["meta"].get("mode", "measured")
        except Exception as exc:  # pragma: no cover
            print(f"[warn] 未能运行真实评测引擎（{type(exc).__name__}: {exc}）。")
            print("[warn] 将只写入压测数据，不产出任何评测指标——不伪造分数。")
    stub = build_preset_benchmark()
    path = DATA_DIR / "benchmark_results.json"
    write_json(path, stub)
    return str(path.relative_to(ROOT)), "unavailable"


